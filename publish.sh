#!/usr/bin/env bash
# Publish woam into the marketing site's public directory, which is what serves
#
#   https://redu.cloud/woam              the tool
#   https://redu.cloud/woam.sha256       its checksum
#   https://redu.cloud/woam-install.sh   the installer
#
# This is a COPY into another repo, which is a drift risk: two files with the same
# name and no link between them. Two things hold it together. The copy carries a
# generated header naming this repo as the source, and the checksum is regenerated
# on every publish, so a hand-edit on the marketing side is visible rather than
# quiet.
#
# It refuses to publish a tool that fails its own tests. Delivery is the one place
# where shipping something broken reaches every machine at once.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEST="${WOAM_PUBLISH_DIR:-$HERE/../redu-marketing/public}"

[ -d "$DEST" ] || { echo "publish: $DEST does not exist. Set WOAM_PUBLISH_DIR." >&2; exit 1; }

echo "publish: running the smoke test first"
bash "$HERE/test/smoke.sh" >/tmp/woam-publish-test.log 2>&1 || {
  echo "publish: REFUSING to publish, test/smoke.sh failed:" >&2
  tail -20 /tmp/woam-publish-test.log >&2
  exit 1
}
echo "publish: tests pass"

# The tool. Copied verbatim: any header injected here would change the file the
# checksum is taken over and would have to be stripped on install.
cp "$HERE/woam" "$DEST/woam"
chmod 0644 "$DEST/woam"

SUM="$(sha256sum "$DEST/woam" | cut -d' ' -f1)"
printf '%s  woam\n' "$SUM" > "$DEST/woam.sha256"

# The installer, with a generated provenance header so nobody edits the copy.
{
  echo "# GENERATED by publish.sh in the woam repo (redu-cloud/woam)."
  echo "# Do not edit this copy. Edit install.sh there and re-run publish.sh."
  tail -n +2 "$HERE/install.sh"
} > "$DEST/woam-install.sh"
chmod 0644 "$DEST/woam-install.sh"

echo
echo "  $DEST/woam              sha256 $SUM"
echo "  $DEST/woam.sha256"
echo "  $DEST/woam-install.sh"
echo
echo "Next: commit these in the marketing repo. They go live when master is merged"
echo "into production, which is what deploys that site."
